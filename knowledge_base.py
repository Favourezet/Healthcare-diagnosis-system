# Some symptoms are a more specific version of another one.
# If a patient has the specific one, they also have the general one.
IMPLIES = {
    "high_fever": "fever",
    "dry_cough": "cough",
    "cough_with_phlegm": "cough",
    "persistent_cough": "cough",
    "coughing_blood": "cough",
    "watery_diarrhoea": "diarrhoea",
    "one_sided_headache": "headache",
    "upper_abdominal_pain": "abdominal_pain",
}


def expand_symptoms(symptoms):
    """Add the general symptom for every specific one (e.g. dry cough -> cough)."""
    result = set(symptoms)
    for s in list(result):
        if s in IMPLIES:
            result.add(IMPLIES[s])
    return result


